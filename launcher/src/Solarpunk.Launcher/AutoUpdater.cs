using System.Diagnostics;
using System.IO.Compression;
using System.Net.Http;
using System.Net.Http.Headers;
using System.Runtime.Versioning;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using Org.BouncyCastle.Crypto.Parameters;
using Org.BouncyCastle.Crypto.Signers;

namespace Solarpunk.Launcher;

/// <summary>
/// Polls a version manifest hosted on Bunny CDN, downloads new builds when
/// available, validates them, and stages them next to the running launcher
/// for a swap-on-exit.
///
/// Manifest format (JSON, served at <see cref="ManifestUrl"/>):
/// {
///   "version": "0.3.0",
///   "release_notes_url": "https://...",
///   "package_url": "https://survivalservers.b-cdn.net/sundial/launcher/...zip",
///   "sha256": "abc...",
///   "signature": "ed25519 hex over version||\n||sha256||\n||package_url",
///   "signature_alg": "ed25519"
/// }
///
/// Security model: HTTPS alone is not enough. A compromised CDN bucket or
/// hijacked DNS could swap the manifest + package and serve arbitrary code.
/// We close that hole with an offline-signed ed25519 manifest: the launcher
/// embeds the public key, the release pipeline signs every manifest with the
/// matching private key, and any manifest without a valid signature is
/// rejected.
///
/// On a successful download + checksum + signature check, the zip is
/// extracted into <c>%LOCALAPPDATA%\Solarpunk\app.pending</c>. A small
/// <c>SolarpunkUpdater.cmd</c> in the install dir is registered to swap
/// directories on next launcher exit, with errorlevel checks + rollback.
/// </summary>
[SupportedOSPlatform("windows")]
public sealed class AutoUpdater
{
    public const string ManifestUrl =
        "https://survivalservers.b-cdn.net/sundial/launcher/manifest.json";

    /// <summary>
    /// Ed25519 public key (32 raw bytes, hex). Paired with the offline
    /// private key under <c>~/.sundial-update-keys/</c> on the release host.
    /// Rotating this is a launcher-release event: customers on older
    /// launchers can't auto-update across a rotation and have to grab a
    /// fresh installer manually.
    /// </summary>
    // Real Solarpunk update-signing ed25519 public key. Paired private key is
    // ~/.sundial-update-keys/sundial-update-ed25519.pem on the release host
    // (generated by scripts/gen-update-keys.sh, used by scripts/sign-and-publish-manifest.sh).
    public const string UpdateSigningPublicKeyHex =
        "f5eefd3ae12b481d4960e7b73e34a64bc09df24a3a31f3f9b9ebeefb5c041a52";

    // The manifest check is a ~300-byte GET against Bunny CDN — turn off
    // Windows WPAD/default-proxy discovery so the cold-start handshake
    // isn't blocked on a non-existent corporate proxy. Earlier this added
    // 5-8 seconds to the first "Check for updates" click in Settings
    // (reported as "10 seconds just to confirm the version was updated").
    // The bundle download in DownloadAndStageAsync uses
    // the same client, so it benefits too.
    private static readonly HttpClient Http = new(new SocketsHttpHandler
    {
        UseProxy = false,
        ConnectTimeout = TimeSpan.FromSeconds(3),
        PooledConnectionLifetime = TimeSpan.FromMinutes(5),
    })
    {
        Timeout = TimeSpan.FromSeconds(20),
    };

    public sealed record Manifest(
        [property: JsonPropertyName("version")] string Version,
        [property: JsonPropertyName("package_url")] string PackageUrl,
        [property: JsonPropertyName("sha256")] string Sha256,
        [property: JsonPropertyName("release_notes_url")] string? ReleaseNotesUrl,
        [property: JsonPropertyName("signature")] string? Signature,
        [property: JsonPropertyName("signature_alg")] string? SignatureAlg);

    public sealed record CheckResult(bool UpdateAvailable, Manifest? Manifest, string? Error);

    public static async Task<CheckResult> CheckAsync(
        string currentVersion,
        CancellationToken ct = default)
    {
        try
        {
            var manifestUrl = $"{ManifestUrl}?t={DateTimeOffset.UtcNow.ToUnixTimeSeconds()}";
            using var req = new HttpRequestMessage(HttpMethod.Get, manifestUrl);
            req.Headers.CacheControl = new CacheControlHeaderValue
            {
                NoCache = true,
                NoStore = true,
            };
            using var resp = await Http.SendAsync(req, HttpCompletionOption.ResponseHeadersRead, ct);
            // Treat 404/manifest-missing as "no updates yet" — common while
            // the update channel is being set up and shouldn't surface as a
            // scary error to the user.
            if (resp.StatusCode == System.Net.HttpStatusCode.NotFound)
                return new CheckResult(false, null, null);
            if (!resp.IsSuccessStatusCode)
                return new CheckResult(false, null, $"server returned HTTP {(int)resp.StatusCode}");

            await using var body = await resp.Content.ReadAsStreamAsync(ct);
            var manifest = await JsonSerializer.DeserializeAsync<Manifest>(body, cancellationToken: ct);
            if (manifest is null || string.IsNullOrWhiteSpace(manifest.Version))
                return new CheckResult(false, null, "manifest parse failed");

            // Verify signature BEFORE comparing versions. A manifest that
            // can't be verified is treated as nonexistent — never act on
            // unsigned/forged manifest data, even to compare versions.
            if (!VerifyManifestSignature(manifest, out var sigError))
                return new CheckResult(false, null, $"manifest signature rejected: {sigError}");

            // Strict greater-than version compare so a same-version manifest
            // doesn't re-download repeatedly.
            return CompareVersions(manifest.Version, currentVersion) > 0
                ? new CheckResult(true, manifest, null)
                : new CheckResult(false, manifest, null);
        }
        catch (Exception ex)
        {
            return new CheckResult(false, null, ex.Message);
        }
    }

    /// <summary>
    /// Verify the manifest's ed25519 signature over the canonical payload
    /// <c>version + "\n" + sha256 + "\n" + package_url</c>. Reject anything
    /// missing a signature, missing the algorithm marker, or whose signature
    /// doesn't validate against the embedded public key.
    /// </summary>
    private static bool VerifyManifestSignature(Manifest m, out string? error)
    {
        if (string.IsNullOrWhiteSpace(m.Signature))
        {
            error = "no signature field";
            return false;
        }
        if (!string.Equals(m.SignatureAlg, "ed25519", StringComparison.OrdinalIgnoreCase))
        {
            error = $"unsupported signature_alg '{m.SignatureAlg}' (expected ed25519)";
            return false;
        }

        byte[] sig;
        try
        {
            sig = Convert.FromHexString(m.Signature);
        }
        catch (FormatException)
        {
            error = "signature is not valid hex";
            return false;
        }
        if (sig.Length != 64)
        {
            error = $"signature length {sig.Length} != 64";
            return false;
        }

        // TODO(solarpunk): the embedded key is still the placeholder until the
        // Solarpunk update keypair + signed-manifest pipeline lands. A non-hex /
        // wrong-length key here just makes every manifest fail verification,
        // which cleanly disables auto-update at runtime instead of throwing at
        // startup. Replace UpdateSigningPublicKeyHex to turn auto-update on.
        byte[] pubKey;
        try
        {
            pubKey = Convert.FromHexString(UpdateSigningPublicKeyHex);
        }
        catch (FormatException)
        {
            error = "update signing key not configured yet (auto-update disabled)";
            return false;
        }
        if (pubKey.Length != 32)
        {
            error = "update signing key not configured yet (auto-update disabled)";
            return false;
        }

        var payload = Encoding.UTF8.GetBytes(
            $"{m.Version}\n{m.Sha256}\n{m.PackageUrl}");

        try
        {
            var verifier = new Ed25519Signer();
            verifier.Init(forSigning: false, new Ed25519PublicKeyParameters(pubKey, 0));
            verifier.BlockUpdate(payload, 0, payload.Length);
            if (!verifier.VerifySignature(sig))
            {
                error = "ed25519 verify failed";
                return false;
            }
        }
        catch (Exception ex)
        {
            error = $"verifier threw: {ex.Message}";
            return false;
        }

        error = null;
        return true;
    }

    public sealed record DownloadResult(bool Success, string? StagedDir, string? Error);

    private static readonly TimeSpan[] PackageDownloadRetryDelays =
    [
        TimeSpan.Zero,
        TimeSpan.FromSeconds(5),
        TimeSpan.FromSeconds(15),
    ];

    /// <summary>
    /// Downloads the package, validates sha256, validates the staged exe's
    /// FileVersion against the manifest, and extracts to a staging dir next
    /// to the installation. Caller is responsible for triggering the swap
    /// (typically on launcher exit, via the SolarpunkUpdater.cmd shim).
    /// </summary>
    public static async Task<DownloadResult> DownloadAndStageAsync(
        Manifest manifest,
        string installRoot,
        CancellationToken ct = default)
    {
        var pendingDir = Path.Combine(installRoot, "app.pending");
        var zipPath = Path.Combine(installRoot, "update.zip");
        try
        {
            if (Directory.Exists(pendingDir))
                Directory.Delete(pendingDir, recursive: true);
            Directory.CreateDirectory(pendingDir);

            var download = await DownloadPackageWithRetriesAsync(manifest.PackageUrl, zipPath, pendingDir, ct)
                .ConfigureAwait(false);
            if (!download.Success)
            {
                return download;
            }

            // Validate checksum
            var actualSha = Convert.ToHexString(
                System.Security.Cryptography.SHA256.HashData(await File.ReadAllBytesAsync(zipPath, ct)))
                .ToLowerInvariant();
            if (!string.Equals(actualSha, manifest.Sha256, StringComparison.OrdinalIgnoreCase))
            {
                return FailDownload(zipPath, pendingDir,
                    $"sha256 mismatch: got {actualSha}, want {manifest.Sha256}");
            }

            ZipFile.ExtractToDirectory(zipPath, pendingDir);
            File.Delete(zipPath);

            // The release pipeline produces a side-load zip with structure
            // {app/, Beacon.dll, ue4ss/, beacon-injector.exe}. The swap
            // script only rotates app/, so if we extracted that zip
            // verbatim we'd end up with app/app/Solarpunk.Launcher.exe. Promote
            // any nested 'app' subdirectory's contents up to pendingDir so
            // the post-swap layout matches what the installer placed at
            // $INSTDIR\app.
            //
            // Order matters: delete non-app siblings (Beacon.dll, ue4ss/,
            // the root-level beacon-injector.exe — side-load extras) BEFORE
            // promoting app/'s contents up. Earlier versions had the order
            // reversed: promote first, then delete siblings — but since
            // beacon-injector.exe also lives INSIDE app/ in the staged
            // zip (the launcher needs it next to the .exe), promoting
            // landed it at pendingDir/beacon-injector.exe, and the
            // subsequent "drop siblings" step then deleted it. That
            // surfaced as "missing Python" at Connect.
            var nestedApp = Path.Combine(pendingDir, "app");
            if (Directory.Exists(nestedApp))
            {
                foreach (var entry in Directory.GetFileSystemEntries(pendingDir))
                {
                    if (string.Equals(Path.GetFileName(entry), "app", StringComparison.OrdinalIgnoreCase))
                        continue;
                    if (File.Exists(entry)) File.Delete(entry);
                    else if (Directory.Exists(entry)) Directory.Delete(entry, recursive: true);
                }
                foreach (var f in Directory.EnumerateFiles(nestedApp, "*", SearchOption.AllDirectories))
                {
                    var rel = Path.GetRelativePath(nestedApp, f);
                    var dest = Path.Combine(pendingDir, rel);
                    Directory.CreateDirectory(Path.GetDirectoryName(dest)!);
                    File.Move(f, dest, overwrite: true);
                }
                Directory.Delete(nestedApp, recursive: true);
            }

            // Staged-package validation: the launcher exe must exist at the
            // expected path AND its FileVersion must match the manifest. If
            // the staged exe is missing or the wrong version, the swap will
            // either brick the install or kick off an update loop on
            // relaunch (manifest says vX but exe says vY → next poll
            // re-downloads). Abort here and surface the mismatch instead.
            var stagedExe = Path.Combine(pendingDir, "Solarpunk.Launcher.exe");
            if (!File.Exists(stagedExe))
            {
                SafeDelete(pendingDir);
                return new DownloadResult(false, null,
                    $"staged package missing Solarpunk.Launcher.exe at {stagedExe}");
            }

            var stagedVersion = ReadAssemblyVersion(stagedExe);
            if (stagedVersion is null)
            {
                SafeDelete(pendingDir);
                return new DownloadResult(false, null,
                    "could not read FileVersion from staged Solarpunk.Launcher.exe");
            }
            if (!VersionMatches(stagedVersion, manifest.Version))
            {
                SafeDelete(pendingDir);
                return new DownloadResult(false, null,
                    $"staged exe version {stagedVersion} != manifest version {manifest.Version}");
            }

            // Drop the swap script — runs after the launcher exits. The
            // script preflights the staged exe AGAIN (the cmd-shell layer
            // runs after the launcher dies, so even if something deleted
            // app.pending between stage and swap, the script will refuse
            // to clobber app/) and rolls back on any rename failure.
            var cmdPath = Path.Combine(installRoot, "SolarpunkUpdater.cmd");
            await File.WriteAllTextAsync(cmdPath, BuildSwapScript(installRoot), ct);

            return new DownloadResult(true, pendingDir, null);
        }
        catch (Exception ex)
        {
            return FailDownload(zipPath, pendingDir,
                MapDownloadException(ex, userCanceled: ct.IsCancellationRequested));
        }
    }

    private static async Task<DownloadResult> DownloadPackageWithRetriesAsync(
        string packageUrl,
        string zipPath,
        string pendingDir,
        CancellationToken ct)
    {
        for (var i = 0; i < PackageDownloadRetryDelays.Length; i++)
        {
            var attempt = i + 1;
            if (PackageDownloadRetryDelays[i] > TimeSpan.Zero)
                await Task.Delay(PackageDownloadRetryDelays[i], ct).ConfigureAwait(false);

            SafeDeleteFile(zipPath);
            long? expectedBytes = null;
            long receivedBytes = 0;

            try
            {
                using var resp = await Http.GetAsync(packageUrl, HttpCompletionOption.ResponseHeadersRead, ct)
                    .ConfigureAwait(false);
                expectedBytes = resp.Content.Headers.ContentLength;
                if (!resp.IsSuccessStatusCode)
                {
                    var retry = IsRetryableStatus(resp.StatusCode) && i + 1 < PackageDownloadRetryDelays.Length;
                    LogPackageAttempt(packageUrl, attempt, receivedBytes, expectedBytes, "HttpStatusCode",
                        retry ? "retry" : "failed");
                    if (retry) continue;
                    return FailDownload(zipPath, pendingDir, $"package HTTP {(int)resp.StatusCode}");
                }

                await using (var rs = await resp.Content.ReadAsStreamAsync(ct).ConfigureAwait(false))
                await using (var fs = File.Create(zipPath))
                {
                    await rs.CopyToAsync(fs, ct).ConfigureAwait(false);
                    receivedBytes = fs.Length;
                }

                receivedBytes = File.Exists(zipPath) ? new FileInfo(zipPath).Length : receivedBytes;
                if (expectedBytes is long expected && receivedBytes != expected)
                {
                    throw new PartialDownloadException(expected, receivedBytes);
                }

                LogPackageAttempt(packageUrl, attempt, receivedBytes, expectedBytes, "none", "success");
                return new DownloadResult(true, null, null);
            }
            catch (Exception ex) when (IsRetryableDownloadException(ex))
            {
                receivedBytes = File.Exists(zipPath) ? new FileInfo(zipPath).Length : receivedBytes;
                var retry = !ct.IsCancellationRequested && i + 1 < PackageDownloadRetryDelays.Length;
                LogPackageAttempt(packageUrl, attempt, receivedBytes, expectedBytes, ex.GetType().Name,
                    retry ? "Network interrupted — retrying" : "failed");
                SafeDeleteFile(zipPath);
                if (retry) continue;
                return FailDownload(zipPath, pendingDir,
                    MapDownloadException(ex, userCanceled: ct.IsCancellationRequested));
            }
            catch (Exception ex)
            {
                receivedBytes = File.Exists(zipPath) ? new FileInfo(zipPath).Length : receivedBytes;
                LogPackageAttempt(packageUrl, attempt, receivedBytes, expectedBytes, ex.GetType().Name, "failed");
                return FailDownload(zipPath, pendingDir,
                    MapDownloadException(ex, userCanceled: ct.IsCancellationRequested));
            }
        }

        return FailDownload(zipPath, pendingDir, "Download failed: connection reset");
    }

    private static DownloadResult FailDownload(string zipPath, string pendingDir, string error)
    {
        SafeDeleteFile(zipPath);
        SafeDelete(pendingDir);
        return new DownloadResult(false, null, error);
    }

    private static bool IsRetryableStatus(System.Net.HttpStatusCode status) =>
        (int)status == 408 || (int)status == 429 || (int)status >= 500;

    private static bool IsRetryableDownloadException(Exception ex) =>
        ex is IOException or HttpRequestException or CryptographicException or OperationCanceledException
        || HasInner<CryptographicException>(ex);

    private static string MapDownloadException(Exception ex, bool userCanceled)
    {
        if (userCanceled) return "Download canceled";
        if (ex is CryptographicException || HasInner<CryptographicException>(ex))
            return "Download failed: TLS error";
        if (ex is OperationCanceledException)
            return "Download failed: timed out";
        if (ex is PartialDownloadException)
            return "Download failed: connection reset";
        if (ex is IOException or HttpRequestException)
            return "Download failed: connection reset";
        return $"Download failed: {ex.GetType().Name}";
    }

    private static bool HasInner<T>(Exception ex)
        where T : Exception
    {
        for (var current = ex.InnerException; current is not null; current = current.InnerException)
        {
            if (current is T) return true;
        }
        return false;
    }

    private static void LogPackageAttempt(
        string packageUrl,
        int attempt,
        long receivedBytes,
        long? expectedBytes,
        string exceptionType,
        string decision)
    {
        SolarpunkLog.Info(
            "AutoUpdater package attempt " +
            $"attempt={attempt}/{PackageDownloadRetryDelays.Length} " +
            $"url={packageUrl} " +
            $"bytes_received={receivedBytes} " +
            $"expected_bytes={(expectedBytes.HasValue ? expectedBytes.Value.ToString() : "unknown")} " +
            $"exception={exceptionType} " +
            $"decision={decision}");
    }

    private sealed class PartialDownloadException(long expectedBytes, long actualBytes) : IOException
    {
        public long ExpectedBytes { get; } = expectedBytes;
        public long ActualBytes { get; } = actualBytes;
    }

    private static void SafeDeleteFile(string path)
    {
        try
        {
            if (File.Exists(path)) File.Delete(path);
        }
        catch
        {
            // Best-effort cleanup; next staging cycle will retry.
        }
    }

    private static void SafeDelete(string dir)
    {
        try
        {
            if (Directory.Exists(dir)) Directory.Delete(dir, recursive: true);
        }
        catch
        {
            // Best-effort cleanup; next staging cycle will retry.
        }
    }

    private static string? ReadAssemblyVersion(string exePath)
    {
        try
        {
            var vi = FileVersionInfo.GetVersionInfo(exePath);
            // FileVersion is what NSIS embeds via VIProductVersion / the
            // .NET assembly publish (Directory.Build.props -> FileVersion).
            // ProductVersion may carry +commit suffixes — FileVersion is
            // the canonical X.Y.Z(.W) string for the comparison.
            return string.IsNullOrWhiteSpace(vi.FileVersion) ? null : vi.FileVersion;
        }
        catch
        {
            return null;
        }
    }

    private static bool VersionMatches(string exeVersion, string manifestVersion)
    {
        // FileVersion typically looks like "0.3.0.0" (X.Y.Z.W) while the
        // manifest is "0.3.0" (X.Y.Z). Match X.Y.Z prefix-wise so the
        // trailing build number doesn't cause spurious mismatches.
        var exParts = exeVersion.Split('.');
        var mfParts = manifestVersion.Split('-', 2)[0].Split('.');
        if (exParts.Length < 3 || mfParts.Length < 3) return false;
        for (var i = 0; i < 3; i++)
        {
            if (!int.TryParse(exParts[i], out var a)) return false;
            if (!int.TryParse(mfParts[i], out var b)) return false;
            if (a != b) return false;
        }
        return true;
    }

    /// <summary>
    /// Spawn the swap script (detached) so it runs after this process exits,
    /// then exits the launcher. The script waits for the launcher to release
    /// its file locks, then replaces <c>app/</c> with <c>app.pending/</c> and
    /// restarts the launcher.
    /// </summary>
    public static void TriggerSwapAndExit(string installRoot)
    {
        var cmd = Path.Combine(installRoot, "SolarpunkUpdater.cmd");
        if (!File.Exists(cmd)) return;

        // Start the .cmd directly (ShellExecute path) and pin WorkingDirectory
        // to the install root. An earlier `cmd.exe /c start "" "..."` form
        // inherited the launcher's PWD, which was $INSTDIR\branding\ for
        // installer-launched sessions (NSIS SetOutPath ordering bug). The
        // staged cmd would then fail with "The batch file cannot be found"
        // and the auto-updater would loop forever — download → close →
        // failed swap → reopen at the old version → re-download.
        System.Diagnostics.Process.Start(new System.Diagnostics.ProcessStartInfo
        {
            FileName = cmd,
            WorkingDirectory = installRoot,
            UseShellExecute = true,
            CreateNoWindow = false,
        });
    }

    private static string BuildSwapScript(string installRoot)
    {
        // The swap script is the most blast-radius-y piece of the updater:
        // if it dies between `ren app -> app.old` and `ren app.pending -> app`,
        // the install is bricked (no app/, customer is stuck on the
        // installer-download path). Defensive shape:
        //
        //   1. Wait for this launcher process to exit (file lock release).
        //   2. Preflight: app.pending\Solarpunk.Launcher.exe must exist. If not,
        //      bail BEFORE renaming anything — leaves app/ intact.
        //   3. Rename app -> app.old, check errorlevel. Rollback if it failed.
        //   4. Rename app.pending -> app, check errorlevel. If THIS fails,
        //      rollback by renaming app.old -> app. (Now we're back at the
        //      old version but at least we're not bricked.)
        //   5. Best-effort cleanup of app.old (the previous app/ tree).
        //   6. Relaunch.
        //
        // A future hardening pass should move the swap into a bootstrapper
        // that lives outside app/ — a .exe whose own integrity isn't tied
        // to the directory it's mutating. For now, errorlevel + rollback
        // closes the bricked-install window for ordinary failure modes
        // (file lock held, AV scan, transient permission issue).
        var app = Path.Combine(installRoot, "app");
        var pending = Path.Combine(installRoot, "app.pending");
        var old = Path.Combine(installRoot, "app.old");
        var stagedExe = Path.Combine(installRoot, "app.pending", "Solarpunk.Launcher.exe");
        var exe = Path.Combine(installRoot, "app", "Solarpunk.Launcher.exe");
        var logPath = Path.Combine(installRoot, "SolarpunkUpdater.log");
        var launcherPid = Environment.ProcessId;

        return $@"@echo off
setlocal EnableDelayedExpansion
cd /D ""{installRoot}""

set ""LOG={logPath}""
set ""LAUNCHER_PID={launcherPid}""
set ""WAIT_SECONDS=0""
echo [%date% %time%] SolarpunkUpdater starting > ""%LOG%"" 2>nul
echo [%date% %time%] Waiting for Solarpunk.Launcher.exe pid !LAUNCHER_PID! to exit. >> ""%LOG%""

:waitloop
tasklist /FI ""PID eq !LAUNCHER_PID!"" /FI ""IMAGENAME eq Solarpunk.Launcher.exe"" 2>nul | find /I ""Solarpunk.Launcher.exe"" >nul
if errorlevel 1 goto waitdone
if !WAIT_SECONDS! GEQ 60 goto waittimeout
ping 127.0.0.1 -n 2 >nul
set /A WAIT_SECONDS+=1
goto waitloop

:waittimeout
echo [%date% %time%] TIMEOUT: pid !LAUNCHER_PID! still running after !WAIT_SECONDS!s; forcing it closed. >> ""%LOG%""
tasklist /FI ""PID eq !LAUNCHER_PID!"" /V >> ""%LOG%"" 2>&1
taskkill /PID !LAUNCHER_PID! /F >> ""%LOG%"" 2>&1
ping 127.0.0.1 -n 3 >nul
tasklist /FI ""PID eq !LAUNCHER_PID!"" /FI ""IMAGENAME eq Solarpunk.Launcher.exe"" 2>nul | find /I ""Solarpunk.Launcher.exe"" >nul
if not errorlevel 1 (
  echo [%date% %time%] ABORT: pid !LAUNCHER_PID! survived taskkill; leaving app/ unchanged. >> ""%LOG%""
  goto :end_fail
)

:waitdone
echo [%date% %time%] Launcher pid !LAUNCHER_PID! is gone after !WAIT_SECONDS!s. >> ""%LOG%""

REM Preflight — refuse to touch app/ if the staged tree is incomplete.
if not exist ""{stagedExe}"" (
  echo [%date% %time%] ABORT: staged exe missing at ""{stagedExe}"" >> ""%LOG%""
  goto :end_fail
)

REM Sweep an old rollback dir from a previous attempt (don't leave stale data).
if exist ""{old}"" (
  rmdir /S /Q ""{old}"" 2>>""%LOG%""
)

REM Step 1: rotate current app/ out of the way.
if exist ""{app}"" (
  ren ""{app}"" app.old
  if errorlevel 1 (
    echo [%date% %time%] ABORT: could not rename app -^> app.old >> ""%LOG%""
    goto :end_fail
  )
)

REM Step 2: promote the staged tree into place.
ren ""{pending}"" app
if errorlevel 1 (
  echo [%date% %time%] FAILED: could not rename app.pending -^> app, rolling back >> ""%LOG%""
  if exist ""{old}"" (
    ren ""{old}"" app
    if errorlevel 1 (
      echo [%date% %time%] ROLLBACK FAILED — install may be bricked. app.old still on disk. >> ""%LOG%""
    ) else (
      echo [%date% %time%] Rollback OK — back on previous version. >> ""%LOG%""
    )
  )
  goto :end_fail
)

REM Step 3: relaunch the new version. Best-effort cleanup of app.old
REM happens after the relaunch is queued so the customer waits as little
REM as possible. The new launcher will tolerate app.old hanging around;
REM nothing in the launcher reads from there.
echo [%date% %time%] Swap OK — relaunching. >> ""%LOG%""
start """" /D ""{installRoot}"" ""{exe}""

if exist ""{old}"" (
  rmdir /S /Q ""{old}"" 2>>""%LOG%""
)

goto :end_ok

:end_fail
