    // Semver-ish compare: split on dots, compare numerically with fallback to
    // lexicographic. Treats prerelease suffixes (-rc1, -beta) as older than
    // their release; good enough for our purposes.
    private static int CompareVersions(string a, string b)
    {
        var ap = a.Split('-', 2);
        var bp = b.Split('-', 2);
        var an = ap[0].Split('.');
        var bn = bp[0].Split('.');
        for (var i = 0; i < Math.Max(an.Length, bn.Length); i++)
        {
            var av = i < an.Length && int.TryParse(an[i], out var x) ? x : 0;
            var bv = i < bn.Length && int.TryParse(bn[i], out var y) ? y : 0;
            if (av != bv) return av.CompareTo(bv);
        }
        // Stable release > prerelease
        var ahasPre = ap.Length > 1;
        var bhasPre = bp.Length > 1;
        if (ahasPre != bhasPre) return ahasPre ? -1 : 1;
        return string.CompareOrdinal(a, b);
    }
